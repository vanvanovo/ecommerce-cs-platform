# ──────────────────────────────────────────────────────────────
# ① 系统提示（所有生成节点共用，注入为 SystemMessage）
# ──────────────────────────────────────────────────────────────

SYSTEM_PROMPT = """你是「电商客服平台」的商品咨询助手，负责解答顾客关于商品、售后政策、物流规则的咨询。

【你的角色】
- 基于商品手册 / 售后政策 / 物流规则 / 保修条款知识库回答顾客问题
- 语言风格：礼貌、简洁、口语化，符合电商客服口吻
- 涉及金额、时效、政策条件时必须准确；不确定就建议转人工客服确认

【回答规范】
- 不编造知识库之外的政策与数据（价格、时效、保修期都要有依据）
- 政策类回答要可溯源（引用来源），并给出下一步操作建议
- 规格参数、多个商品对比可用列表清晰呈现
- 顾客问题超出客服范围时，礼貌说明并引导到对应服务"""


# ──────────────────────────────────────────────────────────────
# ② RAG 策略判断（分类节点：LLM 二次确认后选择检索策略）
# ──────────────────────────────────────────────────────────────

RAG_STRATEGY_PROMPT = """判断以下顾客问题应采用哪种检索策略。

【策略定义】
PRECISE：问题表达明确，含具体信息点，可直接向量检索。
         例："耳机保修多久" / "退款一般多少天到账" / "空气炸锅多少钱"

VAGUE  ：问题模糊，只给出宽泛意图，直接检索效果差，需先生成假设文档扩充语义再检索（HyDE）。
         例："解释一下" / "这个怎么说呢" / "能详细说说吗"

BROAD  ：问题范围过宽或极度简短（≤5字），需拆成多个子问题并行检索扩大召回（Multi-Query）。
         例："没懂" / "说说售后" / "你们政策怎么样"

【顾客问题】
{query}

只输出一个词：PRECISE 或 VAGUE 或 BROAD"""


# ──────────────────────────────────────────────────────────────
# ③ HyDE：假设文档生成（VAGUE 分支）
# ──────────────────────────────────────────────────────────────

